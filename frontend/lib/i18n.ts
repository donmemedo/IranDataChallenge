export const langs = ["fa", "en"] as const;
export type Lang = (typeof langs)[number];

const loc = (l: Lang) => (l === "fa" ? "fa-IR" : "en-US");
export const nf = (l: Lang, n: number, o?: Intl.NumberFormatOptions) => new Intl.NumberFormat(loc(l), o).format(n);
export const df = (l: Lang, iso: string) =>
  new Intl.DateTimeFormat(loc(l), { day: "numeric", month: "long", year: "numeric" }).format(new Date(iso));
export const ago = (l: Lang, iso: string) => {
  const h = Math.round((new Date(iso).getTime() - Date.now()) / 36e5);
  const rtf = new Intl.RelativeTimeFormat(loc(l), { numeric: "auto" });
  return Math.abs(h) < 24 ? rtf.format(h, "hour") : rtf.format(Math.round(h / 24), "day");
};
export const pick = <T extends Record<string, unknown>>(o: T, k: string, l: Lang) => o[`${k}_${l}`] as string;

